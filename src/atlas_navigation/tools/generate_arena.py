"""Generate the fixed, approximate 2027 practice arena and its offline terrain assets."""

import itertools
import math
from pathlib import Path
import random
import struct
import zlib


LENGTH, WIDTH = 6.8, 5.0  # 2027 guidebook §11.2: clear dimensions BETWEEN ducts.
CRATERS = [(6.35, 1.4, .22, .12), (6.35, 2.8, .24, .18), (6.35, 4.3, .25, .24)]
URI = 'model://atlas_navigation/worlds/'


def png(path, width, height, rows, channels=1):
    """Write deterministic 8-bit PNGs without adding image-library dependencies."""
    def chunk(kind, data):
        return (struct.pack('>I', len(data)) + kind + data +
                struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff))

    header = struct.pack('>IIBBBBB', width, height, 8, 0 if channels == 1 else 2, 0, 0, 0)
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', header) +
                     chunk(b'IDAT', zlib.compress(b''.join(b'\0' + row for row in rows), 9)) +
                     chunk(b'IEND', b''))


def terrain(x, y):
    """Rigid surface in metres: millimetric roughness and smooth, negative crater bowls."""
    height = -.0015 * (1 + math.sin(12 * x) * math.sin(13 * y))
    for cx, cy, radius, depth in CRATERS:
        r = math.hypot(x - cx, y - cy) / radius
        if r < 1:
            height -= depth * (1 + math.cos(math.pi * r)) / 2
    return height


def generate(output):
    """Regenerate the world and matching visual/collision assets; all assumptions live here."""
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    n = 257  # Gazebo heightmap side length must be 2^k + 1.
    rows = [bytes(round((terrain(LENGTH * i / (n - 1), WIDTH * (n - 1 - j) / (n - 1)) +
                         .30) / .30 * 255) for i in range(n)) for j in range(n)]
    png(output / 'terrain.png', n, n, rows)
    rng = random.Random(19)
    texture = []
    for _ in range(64):
        row = bytearray()
        for _ in range(64):
            shade = rng.randrange(95, 135)
            row.extend([shade, shade - 3, shade - 8])
        texture.append(bytes(row))
    png(output / 'regolith.png', 64, 64, texture, 3)
    png(output / 'normal.png', 1, 1, [bytes([128, 128, 255])], 3)
    # A slightly irregular icosahedron; its same mesh is used for collision and visual.
    phi = (1 + math.sqrt(5)) / 2
    vertices = [(0, -1, -phi), (0, -1, phi), (0, 1, -phi), (0, 1, phi),
                (-1, -phi, 0), (-1, phi, 0), (1, -phi, 0), (1, phi, 0),
                (-phi, 0, -1), (phi, 0, -1), (-phi, 0, 1), (phi, 0, 1)]
    # Derive the 20 triangular convex faces by supporting planes, preserving winding.
    faces = []
    for a, b, c in itertools.combinations(range(12), 3):
        u = [vertices[b][i] - vertices[a][i] for i in range(3)]
        v = [vertices[c][i] - vertices[a][i] for i in range(3)]
        normal = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
        sides = [sum(normal[i] * (point[i] - vertices[a][i]) for i in range(3))
                 for point in vertices]
        if max(sides) < 1e-8:
            faces.append((a + 1, b + 1, c + 1))
        elif min(sides) > -1e-8:
            faces.append((a + 1, c + 1, b + 1))
    mesh = ['# Deterministic irregular boulder, generated by tools/generate_arena.py']
    positions = []
    for point in vertices:
        scale = rng.uniform(.94, 1.06) / math.sqrt(1 + phi**2)
        positions.append([coordinate * scale for coordinate in point])
        mesh.append('v ' + ' '.join(f'{value:.6f}' for value in positions[-1]))
    for face in faces:
        a, b, c = [positions[index - 1] for index in face]
        u, v = [b[i] - a[i] for i in range(3)], [c[i] - a[i] for i in range(3)]
        normal = [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]]
        magnitude = math.sqrt(sum(value**2 for value in normal))
        mesh.append('vn ' + ' '.join(f'{value / magnitude:.6f}' for value in normal))
    mesh += ['f ' + ' '.join(f'{vertex}//{i}' for vertex in face)
             for i, face in enumerate(faces, 1)]
    (output / 'boulder.obj').write_text('\n'.join(mesh) + '\n')
    models = []

    def body(name, pose, geometry, color='.45 .43 .4 1', collision=True):
        models.append(f'    <model name="{name}"><static>true</static><pose>{pose}</pose>\n'
                      f'      <link name="link">' +
                      (f'<collision name="collision"><geometry>{geometry}</geometry></collision>'
                       if collision else '') +
                      f'<visual name="visual"><geometry>{geometry}</geometry><material>'
                      f'<ambient>{color}</ambient><diffuse>{color}</diffuse></material></visual>'
                      '</link>\n    </model>')

    heightmap = f'<heightmap><uri>{URI}terrain.png</uri><size>{LENGTH} {WIDTH} .30</size>'
    origin = f'{LENGTH/2} {WIDTH/2} -.30'
    texture_xml = (f'<texture><size>1</size><diffuse>{URI}regolith.png</diffuse>'
                   f'<normal>{URI}normal.png</normal></texture><sampling>2</sampling>')
    # Harmonic Ogre2 uses the heightmap origin directly, ignoring its parent pose;
    # DART uses the collision pose instead. These describe the SAME world surface.
    models.append('    <model name="regolith"><static>true</static><link name="link">\n'
                  f'      <collision name="collision"><pose>{origin} 0 0 0</pose>'
                  f'<geometry>{heightmap}<pos>0 0 0</pos></heightmap></geometry>'
                  '<surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>'
                  '</collision>\n'
                  f'      <visual name="visual"><geometry>{heightmap}<pos>{origin}</pos>'
                  f'{texture_xml}</heightmap>'
                  '</geometry></visual>\n    </link></model>')
    # Unknown wall/column/hoist dimensions are illustrative, not NASA specifications.
    walls = [('west', -.22, 2.5, .1, 5.54),
             ('east', 7.02, 2.5, .1, 5.54),
             ('south', 3.4, -.22, 7.14, .1),
             ('north', 3.4, 5.22, 7.14, .1)]
    for name, x, y, length, width in walls:
        body(name + '_wall', f'{x} {y} .5 0 0 0',
             f'<box><size>{length} {width} 1.0</size></box>', '.7 .72 .74 1')
    ducts = [('west', -.085, 2.5, 5.34, math.pi/2, 0),
             ('east', 6.885, 2.5, 5.34, math.pi/2, 0),
             ('south', 3.4, -.085, 6.8, 0, math.pi/2),
             ('north', 3.4, 5.085, 6.8, 0, math.pi/2)]
    for name, x, y, length, roll, pitch in ducts:
        body(name + '_duct', f'{x} {y} .085 {roll} {pitch} 0',
             f'<cylinder><radius>.085</radius><length>{length}</length></cylinder>',
             '.2 .23 .25 1')
    body('central_column', '3.4 2.5 1.5 0 0 0',
         '<box><size>.5 .5 3</size></box>', '.55 .57 .6 1')
    body('overhead_hoist', '3.4 2.5 3.1 0 0 0',
         '<box><size>.25 5.5 .2</size></box>', '.8 .65 .12 1')
    for i, (x, y, z, scale, angle) in enumerate([
            (5.95, .5, .13, '.22 .20 .18', .4),
            (6.05, 2.0, .17, '.20 .22 .23', 1.2),
            (5.95, 4.4, .15, '.22 .21 .20', 2.1)], 1):
        body(f'boulder_{i}', f'{x} {y} {z} .1 .2 {angle}',
             f'<mesh><uri>{URI}boulder.obj</uri><scale>{scale}</scale></mesh>', '.28 .27 .25 1')
    body('excavation_boundary', '2.5 2.5 .005 0 0 0',
         '<box><size>.025 5 .004</size></box>', '.9 .75 .1 .6', False)
    body('starting_zone', '1 1 .005 0 0 0',
         '<box><size>2 2 .002</size></box>', '.15 .4 .75 .25', False)
    # Target coordinates in the guidebook are WALL referenced: subtract the .17 m duct offset.
    body('berm_target', '5.21 .73 .005 0 0 0',
         '<box><size>2.2 .9 .002</size></box>', '.8 .35 .1 .35', False)
    systems = {'physics': 'Physics', 'user-commands': 'UserCommands',
               'scene-broadcaster': 'SceneBroadcaster', 'contact': 'Contact',
               'imu': 'Imu', 'sensors': 'Sensors'}
    plugins = '\n'.join(
        f'    <plugin filename="gz-sim-{filename}-system" name="gz::sim::systems::{name}">' +
        ('<render_engine>ogre2</render_engine>' if name == 'Sensors' else '') + '</plugin>'
        for filename, name in systems.items())
    world = ('<?xml version="1.0"?>\n<!-- Generated by tools/generate_arena.py.\n'
             '2027 NASA guidebook sections 11.1-11.4: approx. 6.8 x 5 m clear interior;\n'
             '.17 m ducts; '
             'rocks/craters randomized in competition. This is one fixed illustrative layout.\n'
             'Column/hoist/walls, crater profiles and rigid regolith contact are approximations.'
             ' -->\n'
             '<sdf version="1.9">\n  <world name="lunabotics_arena">\n'
             '    <gravity>0 0 -9.8</gravity>\n'
             '    <physics name="1ms" type="ignored">'
             '<max_step_size>.001</max_step_size>'
             '<real_time_factor>1</real_time_factor></physics>\n' + plugins + '\n'
             '    <light name="sun" type="directional"><pose>0 0 10 0 0 0</pose>'
             '<diffuse>.8 .8 .8 1</diffuse><direction>-.5 .1 -.9</direction></light>\n' +
             '\n'.join(models) + '\n  </world>\n</sdf>\n')
    (output / 'lunabotics_arena.sdf').write_text(world)


if __name__ == '__main__':
    generate(Path(__file__).resolve().parents[1] / 'worlds')
